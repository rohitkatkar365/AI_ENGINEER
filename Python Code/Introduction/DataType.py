# Use type() to check the type of a variable.

a = 10
# int
print(type(a))

b = 3.142
# float
print(type(b))

name = "RRK"
# string
print(type(name))

flag = True
# bool
print(type(flag))

li = [1,2,3,4]
# List
print(type(li))

t = (1,2,3,4)
# tuple
print(type(t))

s = {1,2,3,4}
# set
print(type(s))

d = {"a":1,"b":2}
# dict
print(type(d))

# O/P
'''
<class 'int'>
<class 'float'>
<class 'str'>
<class 'bool'>
<class 'list'>
<class 'tuple'>
<class 'set'>
<class 'dict'>
'''