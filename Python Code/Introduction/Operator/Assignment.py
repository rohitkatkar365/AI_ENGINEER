'''
| Operator | Example   | Same As      |
| -------- | --------- | ------------ |
| `=`      | `x = 5`   | Assign value |
| `+=`     | `x += 3`  | `x = x + 3`  |
| `-=`     | `x -= 3`  | `x = x - 3`  |
| `*=`     | `x *= 3`  | `x = x * 3`  |
| `/=`     | `x /= 3`  | `x = x / 3`  |
| `%=`     | `x %= 3`  | `x = x % 3`  |
| `//=`    | `x //= 3` | `x = x // 3` |
| `**=`    | `x **= 3` | `x = x ** 3` |
'''

x = 5

x += 5
print(x) # x = 5 + 5 = 10

x -= 5
print(x) # x = 10 - 5 = 5

x *= 5
print(x) # x = 5 * 5 = 25

x /= 5
print(x) # x = 25 / 5 = 5.0

x //= 5
print(x) # x = 5 // 5 = 1.0

x **= 5
print(x) # x = 1 ** 5 = 1.0
