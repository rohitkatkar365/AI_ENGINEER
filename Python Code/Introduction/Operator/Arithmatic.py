'''
| Operator | Meaning             | Example   |
| -------- | ------------------- | --------- |
| `+`      | Addition            | `10 + 5`  |
| `-`      | Subtraction         | `10 - 5`  |
| `*`      | Multiplication      | `10 * 5`  |
| `/`      | Division            | `10 / 5`  |
| `%`      | Modulus (Remainder) | `10 % 3`  |
| `**`     | Exponent (Power)    | `2 ** 3`  |
| `//`     | Floor Division      | `10 // 3` |
'''

a = 10
b = 5

print(a + b)

print(a - b)

print(a * b)

print(a / b)

print(a // b)

print(a ** b)

print(a % b)

