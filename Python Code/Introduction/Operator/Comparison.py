'''
| Operator | Meaning               |
| -------- | --------------------- |
| `==`     | Equal                 |
| `!=`     | Not Equal             |
| `>`      | Greater Than          |
| `<`      | Less Than             |
| `>=`     | Greater Than or Equal |
| `<=`     | Less Than or Equal    |
'''

a = 10
b = 4


print(a == b) # False
print(a > b) # True
print(a >= b) # True
print(a < b) # False
print(a <= b) # False
print(a != b) # True